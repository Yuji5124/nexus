import assert from 'node:assert/strict';
import fs from 'node:fs';
import {MureFight,MURE_CYCLE} from '../src/bossDebug/mureFight.ts';
import {distance} from '../src/bossDebug/arenaFight.ts';
const origin={x:109,y:60,z:-40};
const run=(f,sec)=>{for(let i=0;i<sec/.04;i++){f.tick(.04);f.checkStrike(origin);}};
const bin=fs.statSync(new URL('../assets/models/boss_mure_school.bin',import.meta.url)).size;assert.equal(bin%44,0,'11 float32 per fish');assert.ok(bin/44>=40000);
const f=new MureFight();
f.move(0,-1,0,100);assert.equal(f.player.y,.1);f.move(0,1,0,100);assert.equal(f.player.y,f.ceiling);
f.move(0,0,-1,100);assert.ok(distance(f.player,f.anchor)<=f.tether+1e-4,'tether');
f.reset();assert.equal(f.phase,'drift');run(f,3);assert.equal(f.phase,'gather');
const locked={...f.aim};run(f,4);f.player.x+=30;run(f,.5);assert.deepEqual(f.aim,locked,'aim locks before the stream');
f.reset();f.player={x:109,y:60,z:60};run(f,8.2);assert.equal(f.phase,'stream');assert.equal(f.hp,6,'stream hits once on its line');run(f,1);assert.equal(f.hp,6,'one hit per cycle');
f.reset();run(f,6.6);f.player={x:60,y:60,z:60};run(f,3);assert.equal(f.hp,8,'sideways escape');
f.reset();assert.equal(f.hitBoss(20),false,'melee needs range');f.attackCooldown=0;f.selected=1;assert.ok(f.hitBoss(20));
f.reset();f.time=10;const hp=f.bossHp;assert.equal(f.phase,'molt');f.selected=0;f.hitBoss(0);assert.equal(hp-f.bossHp,3,'molt bonus +1');
f.reset();f.selected=2;for(let i=0;i<100&&!f.won;i++){f.attackCooldown=0;f.hitBoss(0);}assert.ok(f.won);const t=f.time;run(f,1);assert.equal(f.time,t);
f.reset();f.damage(99);assert.ok(f.lost);f.reset();f.invulnerable=true;f.damage(5);assert.equal(f.hp,8);
assert.equal(MURE_CYCLE,16);
console.log('Mure boss: layout size, tether/ceiling, aim lock, stream hit/dodge, molt bonus, victory/loss/reset passed.');
