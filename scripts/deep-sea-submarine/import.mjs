// assets/deep-sea-submarine/*.glb (build_sub_parts.py が作る) と catalog.json から、data/assets.json に collection "deep-sea-submarine" の記録を書く。
// 先に Blender で作る (ライブの Blender MCP でも、ヘッドレスでも):
//   blender -b -P scripts/deep-sea-submarine/build_sub_parts.py -- assets/deep-sea-submarine thumbnails/deep-sea-submarine
// 続けて:  npm run deep-sea-submarine   (この import と scan。scan だけを先に走らせると記録が重複するので、必ずこの順で)
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { NodeIO } from '@gltf-transform/core';
import { getBounds } from '@gltf-transform/functions';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '../..');
const dataFile = path.join(root, 'data/assets.json');
const COLLECTION = 'deep-sea-submarine';
const catalog = JSON.parse(await fs.readFile(path.join(here, 'catalog.json'), 'utf8'));
const KIND_TAGS = { hull: ['hull', 'pressure'], propulsion: ['propulsion'], sensor: ['sensor'], light: ['light'], tool: ['tool', 'work'], crew: ['crew', 'cabin'] };
const GLASS = new Set(['sub_headlamp', 'sub_dome_viewport', 'sub_sample_rack']);

const io = new NodeIO();
const records = [];
for (const c of catalog) {
  const rel = `assets/${COLLECTION}/${c.id}.glb`;
  let stat;
  try { stat = await fs.stat(path.join(root, rel)); } catch { console.warn(`missing ${rel} (run build_sub_parts.py first)`); continue; }
  const doc = await io.read(path.join(root, rel));
  const b = getBounds(doc.getRoot().listScenes()[0]);
  const size = b.max.map((v, i) => Number((v - b.min[i]).toFixed(2)));
  const glass = GLASS.has(c.id);
  records.push({
    id: c.id, name: c.name, title: c.name, collection: COLLECTION, category: 'submarine', subcategory: c.kind, format: 'GLB', type: 'model',
    tags: [...new Set([COLLECTION, 'deep-sea', 'submarine', 'lowpoly', 'upgrade', ...KIND_TAGS[c.kind], ...c.tags])],
    gameRoles: c.roles, climbable: false, animated: false,
    description: `${c.description} ${size[0]} × ${size[1]} × ${size[2]} m (W × H × D). Scaled for the 14 m submarine of the game; design only (stats, prices and tiers are not decided).`,
    file: rel, localPath: rel, thumbnail: `thumbnails/${COLLECTION}/${c.id}.png`,
    license: 'UNKNOWN', author: 'Yuji5124 (NEXUS original)', source: 'NEXUS original (scripts/deep-sea-submarine)',
    sourceUrl: `https://github.com/Yuji5124/nexus/tree/main/scripts/${COLLECTION}`,
    licenseEvidence: 'Original model generated by scripts/deep-sea-submarine/build_sub_parts.py (Blender, built through Blender MCP); no third-party meshes, images or code. The parts follow the submarine growth list (hull, engine, sonar, light, cargo, arm) in the crustaceans-have-plans GAME_SPEC. No licence declared yet.',
    units: { metresPerUnit: 1, nativeSize: size, suggestedSizeMetres: size, upAxis: 'Y' },
    optimization: { tool: 'Blender glTF exporter; flat shading, no textures', outputBytes: stat.size },
    notes: (c.kind === 'hull'
      ? 'Hull section: origin at the centre, long axis along Z (bow toward +Z), 1 unit = 1 m. '
      : 'Mounting part: origin at the attach point, outward = +Y, bow toward +Z, 1 unit = 1 m. ')
      + 'Materials: hull / dark / accent (orange) / brass / gold / shell (purple) / rubber are opaque; glow (cyan) and warm (lamp) are emissive, so enable bloom.'
      + (glass ? ' The glass material uses alphaMode BLEND: draw it in the transparent pass.' : ''),
    recommendedFor: ['threejs', 'lowpoly', 'submarine', 'underwater', 'deep-sea', 'game-level'], addedAt: '2026-11-04T00:00:00.000Z'
  });
}
const index = JSON.parse(await fs.readFile(dataFile, 'utf8')).filter((a) => a.collection !== COLLECTION);
await fs.writeFile(dataFile, JSON.stringify([...index, ...records], null, 2) + '\n');
console.log(`Registered ${records.length} ${COLLECTION} models.`);
