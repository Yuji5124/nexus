// assets/deep-sea-ruins/*.glb (build_ruins.py が作る) から、data/assets.json に collection "deep-sea-ruins" の記録を書く。
// 先に Blender で作る:  blender -b -P scripts/deep-sea-ruins/build_ruins.py -- assets/deep-sea-ruins thumbnails/deep-sea-ruins
// 続けて:               npm run deep-sea-ruins   (この import と scan)
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { NodeIO } from '@gltf-transform/core';
import { getBounds } from '@gltf-transform/functions';
import { catalog } from './catalog.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const dataFile = path.join(root, 'data/assets.json');
const COLLECTION = 'deep-sea-ruins';
const KIND_LABEL = { structure: 'structure', floor: 'floor', decor: 'decor', rubble: 'rubble', station: 'station', bio: 'bio' };

const io = new NodeIO();
const records = [];
for (const c of catalog) {
  const rel = `assets/${COLLECTION}/${c.id}.glb`;
  const file = path.join(root, rel);
  let stat;
  try { stat = await fs.stat(file); } catch { console.warn(`missing ${rel} (run build_ruins.py first)`); continue; }
  const doc = await io.read(file);
  const b = getBounds(doc.getRoot().listScenes()[0]);
  const size = b.max.map((v, i) => Number((v - b.min[i]).toFixed(2)));
  records.push({
    id: c.id, name: c.name, title: c.name, collection: COLLECTION, category: 'ruins', subcategory: KIND_LABEL[c.kind], format: 'GLB', type: 'model',
    tags: [...new Set([COLLECTION, 'ruins', 'ancient', 'deep-sea', 'lowpoly', 'modular', 'glyph', 'emissive', c.kind, ...c.tags])],
    gameRoles: c.roles, climbable: false, animated: false,
    description: `${c.description} ${size[0]} × ${size[1]} × ${size[2]} m (W × H × D).`,
    file: rel, localPath: rel, thumbnail: `thumbnails/${COLLECTION}/${c.id}.png`,
    license: 'UNKNOWN', author: 'Yuji5124 (NEXUS original)', source: 'NEXUS original (scripts/deep-sea-ruins)',
    sourceUrl: `https://github.com/Yuji5124/nexus/tree/main/scripts/${COLLECTION}`,
    licenseEvidence: 'Original model generated by scripts/deep-sea-ruins/build_ruins.py (Blender); no third-party meshes, images or code. Design reference only: modular-kit conventions of CC0 packs (KayKit Dungeon Remastered, Kenney kits). No licence declared yet.',
    units: { metresPerUnit: 1, nativeSize: size, suggestedSizeMetres: size, upAxis: 'Y' },
    optimization: { tool: 'Blender glTF exporter; flat shading, vertex-colour weathering, no textures', outputBytes: stat.size },
    notes: 'Origin at the centre of the base (bottom at y = 0), 1 unit = 1 m, front faces +Z. Stone uses vertex colours (darker, mossy at the bottom); glyphs/lamps are emissive materials (cyan / amber / green), so enable bloom for the glow. Each model is 2–4 meshes (stone + glow [+ warm, bio]).',
    recommendedFor: ['threejs', 'lowpoly', 'ruins', 'underwater', 'deep-sea', 'game-level'], addedAt: '2026-11-03T00:00:00.000Z'
  });
}
const index = JSON.parse(await fs.readFile(dataFile, 'utf8')).filter((a) => a.collection !== COLLECTION);
await fs.writeFile(dataFile, JSON.stringify([...index, ...records], null, 2) + '\n');
console.log(`Registered ${records.length} ${COLLECTION} models.`);
