// assets/deep-trench-enemies/*.glb (build_trench_enemies.py が作る) から、data/assets.json に collection "deep-trench-enemies" の記録を書く。
// 先に Blender で作る:  blender -b -P scripts/deep-trench-enemies/build_trench_enemies.py -- assets/deep-trench-enemies thumbnails/deep-trench-enemies
// 続けて:               npm run deep-trench-enemies   (この import と scan)
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { NodeIO } from '@gltf-transform/core';
import { getBounds } from '@gltf-transform/functions';
import { catalog, ZONES } from './catalog.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const dataFile = path.join(root, 'data/assets.json');
const COLLECTION = 'deep-trench-enemies';
const io = new NodeIO();
const records = [];
for (const c of catalog) {
  const rel = `assets/${COLLECTION}/${c.id}.glb`;
  let stat;
  try { stat = await fs.stat(path.join(root, rel)); } catch { console.warn(`missing ${rel} (run build_trench_enemies.py first)`); continue; }
  const doc = await io.read(path.join(root, rel));
  const b = getBounds(doc.getRoot().listScenes()[0]);
  const size = b.max.map((v, i) => Number((v - b.min[i]).toFixed(2)));
  const clips = doc.getRoot().listAnimations().map((a) => a.getName()).sort();
  records.push({
    id: c.id, name: c.name, title: c.name, collection: COLLECTION, category: 'enemy', subcategory: c.move, format: 'GLB', type: 'model',
    tags: [...new Set([COLLECTION, 'enemy', 'monster', 'deep-sea', 'deep-trench', c.zone, 'lowpoly', 'rigged', 'animated', c.move, c.tier, ...c.tags])],
    gameRoles: ['enemy', ...(c.tier === 'elite' ? ['elite'] : []), ...(c.move === 'static' ? ['hazard'] : [])], climbable: false, animated: true,
    description: `${c.description} Clips: ${clips.join(', ')}. ${size[0]} × ${size[1]} × ${size[2]} m (W × H × D). Suggested depth: ${ZONES[c.zone].range} (${ZONES[c.zone].label}; a proposal, not a spec). Design hint: ${c.hint}`,
    file: rel, localPath: rel, thumbnail: `thumbnails/${COLLECTION}/${c.id}.png`,
    license: 'UNKNOWN', author: 'Yuji5124 (NEXUS original)', source: 'NEXUS original (scripts/deep-trench-enemies)',
    sourceUrl: `https://github.com/Yuji5124/nexus/tree/main/scripts/${COLLECTION}`,
    licenseEvidence: 'Original model and animation generated by scripts/deep-trench-enemies/build_trench_enemies.py (Blender); no third-party meshes, images or code. Design follows the depth bands and phenomena in the crustaceans-have-plans docs (GAME_SPEC / UNKNOWN_NATURAL_PHENOMENA); shapes are original, no third-party assets. No licence declared yet.',
    units: { metresPerUnit: 1, nativeSize: size, suggestedSizeMetres: size, upAxis: 'Y' },
    optimization: { tool: 'Blender glTF exporter; rigid-part armature (no skinning), flat shading, no textures', outputBytes: stat.size },
    notes: 'Origin at the feet (flying / swimming enemies: at their rest height, see boundingBox). Front faces +Z, 1 unit = 1 m. Every part is parented to a bone (rigid, no skinning), so each part is its own node under the bone node; play clips with THREE.AnimationMixer by name (Idle always; Walk / Swim / Attack where listed). Materials: hull, armor, accent (orange), eye (red emissive), glow (cyan), lume (violet emissive), amber (warm emissive), bone, stone / rune, glass and ghost (alpha blend). Enable bloom for the glow.',
    recommendedFor: ['threejs', 'lowpoly', 'enemy', 'underwater', 'deep-sea', 'game-level'], addedAt: '2026-11-03T00:00:00.000Z'
  });
}
const index = JSON.parse(await fs.readFile(dataFile, 'utf8')).filter((a) => a.collection !== COLLECTION);
await fs.writeFile(dataFile, JSON.stringify([...index, ...records], null, 2) + '\n');
console.log(`Registered ${records.length} ${COLLECTION} models.`);
