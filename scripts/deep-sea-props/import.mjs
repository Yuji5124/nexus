// assets/deep-sea-props/*.glb (build_props.py が作る) と catalog.json から、data/assets.json に collection "deep-sea-props" の記録を書く。
// 先に Blender で作る:  blender -b -P scripts/deep-sea-props/build_props.py -- assets/deep-sea-props thumbnails/deep-sea-props
// 続けて:               npm run deep-sea-props   (この import と scan)
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { NodeIO } from '@gltf-transform/core';
import { getBounds } from '@gltf-transform/functions';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '../..');
const dataFile = path.join(root, 'data/assets.json');
const COLLECTION = 'deep-sea-props';
const catalog = JSON.parse(await fs.readFile(path.join(here, 'catalog.json'), 'utf8'));
const CATEGORY = { effect: 'effect', item: 'item', prop: 'prop' };
const KIND_TAGS = { effect: ['effect', 'vfx', 'translucent'], item: ['item', 'pickup', 'collectible'], prop: ['prop', 'terrain', 'scenery'] };

const io = new NodeIO();
const records = [];
for (const c of catalog) {
  const rel = `assets/${COLLECTION}/${c.id}.glb`;
  let stat;
  try { stat = await fs.stat(path.join(root, rel)); } catch { console.warn(`missing ${rel} (run build_props.py first)`); continue; }
  const doc = await io.read(path.join(root, rel));
  const b = getBounds(doc.getRoot().listScenes()[0]);
  const size = b.max.map((v, i) => Number((v - b.min[i]).toFixed(2)));
  const translucent = c.kind === 'effect';
  records.push({
    id: c.id, name: c.name, title: c.name, collection: COLLECTION, category: CATEGORY[c.kind], subcategory: c.kind, format: 'GLB', type: 'model',
    tags: [...new Set([COLLECTION, 'deep-sea', 'lowpoly', ...KIND_TAGS[c.kind], ...c.tags])],
    gameRoles: c.roles, climbable: false, animated: false,
    description: `${c.description} ${size[0]} × ${size[1]} × ${size[2]} m (W × H × D).`,
    file: rel, localPath: rel, thumbnail: `thumbnails/${COLLECTION}/${c.id}.png`,
    license: 'UNKNOWN', author: 'Yuji5124 (NEXUS original)', source: 'NEXUS original (scripts/deep-sea-props)',
    sourceUrl: `https://github.com/Yuji5124/nexus/tree/main/scripts/${COLLECTION}`,
    licenseEvidence: 'Original model generated by scripts/deep-sea-props/build_props.py (Blender); no third-party meshes, images or code. No licence declared yet.',
    units: { metresPerUnit: 1, nativeSize: size, suggestedSizeMetres: size, upAxis: 'Y' },
    optimization: { tool: 'Blender glTF exporter; flat shading, vertex-colour weathering on stone, no textures', outputBytes: stat.size },
    notes: translucent
      ? 'Effect mesh: the beam / glass materials use alphaMode BLEND and are emissive. In Three.js render them in the transparent pass with depthWrite = false (and AdditiveBlending if you want a glowing look), then scale / rotate / fade them in code. Origin at the effect\'s base or reference point, front faces +Z, 1 unit = 1 m.'
      : 'Origin at the centre of the base (bottom at y = 0), front faces +Z, 1 unit = 1 m. Stone uses vertex colours (weathering); glow / warm / bio parts are emissive, so enable bloom.',
    recommendedFor: ['threejs', 'lowpoly', 'underwater', 'deep-sea', translucent ? 'vfx' : 'game-level'], addedAt: '2026-11-03T00:00:00.000Z'
  });
}
const index = JSON.parse(await fs.readFile(dataFile, 'utf8')).filter((a) => a.collection !== COLLECTION);
await fs.writeFile(dataFile, JSON.stringify([...index, ...records], null, 2) + '\n');
console.log(`Registered ${records.length} ${COLLECTION} models.`);
