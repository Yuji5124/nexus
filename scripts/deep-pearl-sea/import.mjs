// assets/deep-pearl-sea/*.glb (build_pearl_parts.py が作る) と catalog.json から、data/assets.json に collection "deep-pearl-sea" の記録を書く。
// 先に Blender で作る (ライブの Blender MCP でも、ヘッドレスでも):
//   blender -b -P scripts/deep-pearl-sea/build_pearl_parts.py -- assets/deep-pearl-sea thumbnails/deep-pearl-sea
// 続けて:  npm run deep-pearl-sea   (この import と scan。scan だけを先に走らせると記録が重複するので、必ずこの順で)
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { NodeIO } from '@gltf-transform/core';
import { getBounds } from '@gltf-transform/functions';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '../..');
const dataFile = path.join(root, 'data/assets.json');
const COLLECTION = 'deep-pearl-sea';
const catalog = JSON.parse(await fs.readFile(path.join(here, 'catalog.json'), 'utf8'));
const KIND_TAGS = { prop: ['prop', 'scenery', 'terrain'], effect: ['effect', 'vfx'], fauna: ['fauna', 'ambient'] };

const io = new NodeIO();
const records = [];
for (const c of catalog) {
  const rel = `assets/${COLLECTION}/${c.id}.glb`;
  let stat;
  try { stat = await fs.stat(path.join(root, rel)); } catch { console.warn(`missing ${rel} (run build_pearl_parts.py first)`); continue; }
  const doc = await io.read(path.join(root, rel));
  const b = getBounds(doc.getRoot().listScenes()[0]);
  const size = b.max.map((v, i) => Number((v - b.min[i]).toFixed(2)));
  const translucent = c.tags.includes('alpha');
  records.push({
    id: c.id, name: c.name, title: c.name, collection: COLLECTION, category: c.kind === 'fauna' ? 'fauna' : (c.kind === 'effect' ? 'effect' : 'prop'), subcategory: c.kind, format: 'GLB', type: 'model',
    tags: [...new Set([COLLECTION, 'deep-sea', 'pearl-sea', 'lowpoly', ...KIND_TAGS[c.kind], ...c.tags])],
    gameRoles: c.roles, climbable: false, animated: false,
    description: `${c.description} ${size[0]} × ${size[1]} × ${size[2]} m (W × H × D). Suggested depth: around 4,500 m (milky pearl sea; a proposal, not a spec).`,
    file: rel, localPath: rel, thumbnail: `thumbnails/${COLLECTION}/${c.id}.png`,
    license: 'UNKNOWN', author: 'Yuji5124 (NEXUS original)', source: 'NEXUS original (scripts/deep-pearl-sea)',
    sourceUrl: `https://github.com/Yuji5124/nexus/tree/main/scripts/${COLLECTION}`,
    licenseEvidence: 'Original model generated by scripts/deep-pearl-sea/build_pearl_parts.py (Blender, built through Blender MCP); no third-party meshes, images or code. The shapes follow the 4,500 m milky-sea concept brief of the crustaceans-have-plans game (background only; the boss is not modelled here). No licence declared yet.',
    units: { metresPerUnit: 1, nativeSize: size, suggestedSizeMetres: size, upAxis: 'Y' },
    optimization: { tool: 'Blender glTF exporter; flat shading, no textures', outputBytes: stat.size },
    notes: 'Origin at the centre of the base (bottom at y = 0), front faces +Z, 1 unit = 1 m. pearl / nacre / pink / jade are opaque with a faint emission, so a little bloom suits them.'
      + (translucent ? ' Translucent: the glass / leaf / dust / veil / rosev / jadev materials use alphaMode BLEND and are emissive; draw them in the transparent pass with depthWrite = false.' : '')
      + (c.kind === 'fauna' ? ' Fish are meant to be instanced; they are ordinary small fish, not the boss body.' : ''),
    recommendedFor: ['threejs', 'lowpoly', 'underwater', 'deep-sea', translucent ? 'vfx' : 'game-level'], addedAt: '2026-11-05T00:00:00.000Z'
  });
}
const index = JSON.parse(await fs.readFile(dataFile, 'utf8')).filter((a) => a.collection !== COLLECTION);
await fs.writeFile(dataFile, JSON.stringify([...index, ...records], null, 2) + '\n');
console.log(`Registered ${records.length} ${COLLECTION} models.`);
