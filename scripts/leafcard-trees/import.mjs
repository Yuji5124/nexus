// Builds the five leaf-card trees into assets/leafcard-trees/, renders thumbnails
// and writes their records (collection "leafcard-trees") into data/assets.json.
// Run `npm run scan` afterwards (`npm run leafcard-trees` does both).
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { NodeIO } from '@gltf-transform/core';
import { getBounds } from '@gltf-transform/functions';
import { build } from './build.mjs';
import { renderThumbnails } from '../giant-climb/thumbnails.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const outDir = path.join(root, 'assets/leafcard-trees');
const thumbDir = path.join(root, 'thumbnails/leafcard-trees');
const dataFile = path.join(root, 'data/assets.json');

await fs.rm(outDir, { recursive: true, force: true });
const built = await build(outDir), io = new NodeIO(), records = [];
for (const t of built) {
  const rel = path.relative(root, t.file).split(path.sep).join('/');
  const doc = await io.read(t.file), b = getBounds(doc.getRoot().listScenes()[0]);
  const size = b.max.map((v, i) => Number((v - b.min[i]).toFixed(2)));
  records.push({
    id: t.id, name: t.name, title: t.name, collection: 'leafcard-trees', category: 'tree', subcategory: 'tree', format: 'GLB', type: 'model',
    tags: [...new Set(['leafcard-trees', 'tree', 'lowpoly', 'nature', 'leaf-cards', 'billboard', 'alpha-mask', 'textured', 'lightweight', ...t.tags])],
    gameRoles: ['scenery', 'obstacle'], climbable: false, animated: false,
    description: `${t.description} ${t.triangles} triangles: trunk ${t.trunkTriangles}, ${t.cards} leaf-card quads. Two materials: painted bark (128×256 JPEG) and a 512 px leaf atlas with four cluster variants (alpha mask, double-sided).`,
    file: rel, localPath: rel, thumbnail: `thumbnails/leafcard-trees/${t.id}.png`,
    license: 'UNKNOWN', author: 'Yuji5124 (NEXUS original)', source: 'NEXUS original (scripts/leafcard-trees)',
    sourceUrl: 'https://github.com/Yuji5124/nexus/tree/main/scripts/leafcard-trees',
    licenseEvidence: 'Original model generated by scripts/leafcard-trees/build.mjs; every texture is painted by the script, no third-party images or meshes. Technique after EZ-Tree (github.com/dgreenheck/ez-tree, MIT): crossed "double billboard" leaf cards with alpha test; no EZ-Tree code or assets are included. No licence declared yet.',
    units: { metresPerUnit: 1, nativeSize: size, suggestedSizeMetres: size, upAxis: 'Y' },
    optimization: { tool: 'Built directly as glTF (glTF Transform 4); leaf atlas PNG palette-quantised, bark JPEG q82', outputBytes: t.bytes },
    notes: 'Leaves use alphaMode MASK (cutoff 0.5) and are double-sided; card normals point away from the crown centre for soft shading. Keep them in the opaque pass (no sorting needed). Origin at the base of the trunk, 1 unit = 1 m.',
    recommendedFor: ['threejs', 'lowpoly', 'nature', 'forest', 'mobile'], addedAt: '2026-10-24T00:00:00.000Z'
  });
}
await fs.rm(thumbDir, { recursive: true, force: true });
await renderThumbnails(thumbDir, records.map(r => path.join(root, r.file)));
const index = JSON.parse(await fs.readFile(dataFile, 'utf8')).filter(a => a.collection !== 'leafcard-trees');
await fs.writeFile(dataFile, JSON.stringify([...index, ...records], null, 2) + '\n');
console.log(`Built ${records.length} leaf-card trees.`);
