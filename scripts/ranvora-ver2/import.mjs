const git = (cwd, ...args) => execFileSync('git', args, { cwd, stdio: ['ignore', 'pipe', 'inherit'] }).toString().trim();
const sha256 = data => crypto.createHash('sha256').update(data).digest('hex');
const exists = file => fs.access(file).then(() => true, () => false);

async function sourceDir() {
  const dir = process.env.RANVORA_VER2_DIR ? path.resolve(process.env.RANVORA_VER2_DIR) : path.join(root, '.cache/ranvora-ver2');
  if (!process.env.RANVORA_VER2_DIR) {
    if (!(await exists(path.join(dir, '.git')))) {
      await fs.mkdir(dir, { recursive: true });
      git(dir, 'init', '-q'); git(dir, 'remote', 'add', 'origin', REPO);
    }
    git(dir, 'fetch', '-q', '--depth', '1', 'origin', COMMIT);
    git(dir, 'checkout', '-q', 'FETCH_HEAD');
  }
  if (git(dir, 'rev-parse', 'HEAD') !== COMMIT) throw new Error(`${dir} is not at ${COMMIT}`);
  if (!(await exists(path.join(dir, 'node_modules/three')))) execFileSync('npm', ['ci', '--no-audit', '--no-fund'], { cwd: dir, stdio: 'inherit' });
  return dir;
}

const io = new NodeIO().registerExtensions(ALL_EXTENSIONS);

async function writeGlb(document, rel, optimise) {
  if (optimise) await document.transform(dedup(), weld(), prune());
  const glb = Buffer.from(await io.writeBinary(document));
  await fs.mkdir(path.dirname(path.join(root, rel)), { recursive: true });
  await fs.writeFile(path.join(root, rel), glb);
  const scene = document.getRoot().listScenes()[0], b = getBounds(scene);
  return { glb, size: b.max.map((v, i) => Number((v - b.min[i]).toFixed(3))), clips: document.getRoot().listAnimations().map(a => a.getName()) };
}

