const exporterPage = `<!doctype html><html><body><script type="module" src="./entry.js"></script></body></html>`;

async function buildExporter(src) {
  const work = path.join(root, '.cache/ranvora-ver2-exporter');
  await fs.rm(work, { recursive: true, force: true });
  await fs.mkdir(work, { recursive: true });
  await fs.copyFile(path.join(here, 'exporter/entry.js'), path.join(work, 'entry.js'));
  await fs.writeFile(path.join(work, 'index.html'), exporterPage);
  await fs.symlink(path.join(src, 'node_modules'), path.join(work, 'node_modules'), 'dir');
  const viteEntry = createRequire(path.join(src, 'package.json')).resolve('vite');
  const { build } = await import(pathToFileURL(viteEntry).href);
  await build({ root: work, configFile: false, logLevel: 'warn', base: './', resolve: { alias: { '@ver2': path.join(src, 'src') } }, build: { outDir: path.join(work, 'dist'), target: 'es2022', chunkSizeWarningLimit: 8000 } });
  return path.join(work, 'dist');
}

async function exportProcedural(src) {
  const dist = await buildExporter(src);
  const mime = { '.js': 'text/javascript', '.html': 'text/html', '.css': 'text/css', '.wasm': 'application/wasm' };
  const server = http.createServer(async (req, res) => {
    const rel = decodeURIComponent(new URL(req.url, 'http://x').pathname);
    const file = path.resolve(dist, '.' + (rel === '/' ? '/index.html' : rel));
    if (!file.startsWith(dist + path.sep)) { res.writeHead(403); return res.end(); }
    try { const data = await fs.readFile(file); res.writeHead(200, { 'content-type': mime[path.extname(file)] || 'application/octet-stream' }); res.end(data); }
    catch { res.writeHead(404); res.end(); }
  });
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  let playwright;
  try { playwright = await import('playwright'); } catch {
    const globalRoot = execFileSync('npm', ['root', '-g']).toString().trim();
    playwright = await import(pathToFileURL(createRequire(path.join(globalRoot, 'noop.js')).resolve('playwright')).href);
  }
  const chromium = playwright.chromium || playwright.default.chromium;
  const browser = await chromium.launch({ args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
  const page = await browser.newPage();
  const errors = []; page.on('pageerror', e => errors.push(e.message));
  await page.goto(`http://127.0.0.1:${server.address().port}/`);
  await page.waitForFunction(() => window.ready, null, { timeout: 60000 }).catch(() => { throw new Error(`exporter page failed: ${errors.join('; ')}`); });
  const result = await page.evaluate(() => window.exportAll());
  await browser.close(); server.close();
  return result;
}

async function importProcedural(src) {
  const exported = await exportProcedural(src);
  const records = [];
  const write = async (key, rel) => {
    const raw = Buffer.from(exported[key].glb, 'base64');
    const out = await writeGlb(await io.readBinary(new Uint8Array(raw)), rel, true);
    return { ...out, raw };
  };

  for (const [key, [title, description, tags]] of Object.entries(PROPS)) {
    const id = `ranvora_v2_${key.replace(/[A-Z]/g, c => '_' + c.toLowerCase())}`;
    const isTree = tags.includes('tree'), category = isTree ? 'tree' : tags.includes('rock') ? 'rock' : 'plant';
    const rel = `assets/ranvora-ver2/nature/${id}.glb`;
    const { glb, size, raw } = await write(key, rel);
    const variants = exported[key].variants;
    records.push(record({
      id, name: `RANVORA ver2 ${title}`, category, file: rel,
      tags: ['nature', 'procedural', 'flat-shaded', 'vertex-colors', 'variants', ...tags],
      gameRoles: ['scenery', ...(isTree || key === 'crag' || key === 'rock' ? ['obstacle'] : ['decoration'])], animated: false,
      description: `${description} ${variants} variants (${Array.from({ length: variants }, (_, i) => `${key}_${String.fromCharCode(65 + i)}`).join(', ')}), one root child each, laid out in a row along +X. Single vertex-coloured material, origin of each variant = ground contact point.`,
      sourceFile: 'src/world/Props.ts', input: null, glb, size,
      units: { metresPerUnit: 1, nativeSize: size, suggestedSizeMetres: size, upAxis: 'Y' },
      optimization: { tool: 'three.js GLTFExporter (RANVORA ver2 ProceduralProps, default seed) → glTF Transform 4: dedup, weld, prune', sourceBytes: raw.length, outputBytes: glb.length },
      notes: `Built by RANVORA ver2's ProceduralProps.${key}() with its default seed, so it matches the game exactly. Root child = variant, as in RANVORA ver2's GLB rule: register it as MODEL_OVERRIDES.${key} in src/assets/manifest.ts (AssetLoader.toPropSource ignores the row offsets). To place one variant elsewhere, take a root child and reset its X position.`,
      extra: { variants, ranvoraPropKey: key }
    }));
  }

  {
    const rel = 'assets/ranvora-ver2/buildings/ranvora_v2_log_cabin.glb';
    const { glb, size, raw } = await write('cabin', rel);
    records.push(record({
      id: 'ranvora_v2_log_cabin', name: 'RANVORA ver2 Log Cabin', category: 'building', file: rel,
      tags: ['building', 'cabin', 'log-cabin', 'house', 'interior', 'furnished', 'wood', 'fireplace', 'porch', 'textured'],
      gameRoles: ['building', 'interior', 'landmark'], animated: false,
      description: 'Enterable realistic-leaning log cabin (interior 8 × 6.4 m): saddle-notched logs with chinking, thick gable roof with shingles, covered porch with steps and railing, stone chimney, shuttered windows with flower boxes, open plank door, woodpile and bench. Inside: fireplace with flames, exposed beams, kitchen counter, table with four chairs, quilted bed, bookshelf, rug, armchair and lantern. Code-drawn textures embedded. Origin = cabin centre at ground level, front (porch) faces +Z.',
      sourceFile: 'src/world/Cabin.ts', input: null, glb, size,
      units: { metresPerUnit: 1, nativeSize: size, suggestedSizeMetres: size, upAxis: 'Y', front: '+Z', floorHeight: 0.6 },
      optimization: { tool: 'three.js GLTFExporter (createCabin(WORLD.seed + 41)) → glTF Transform 4: dedup, weld, prune', sourceBytes: raw.length, outputBytes: glb.length },
      notes: `Same seed as the RANVORA ver2 world (WORLD.seed + 41 = 1378). Removed for export: ${exported.cabin.removedLights} point lights (fireplace and lantern) and the flame flicker, which live in code. Bump maps are not part of glTF and are dropped; colour textures are kept. Collision boxes and floor heights are in Cabin.ts, not in the GLB.`
    }));
  }

  for (const [key, id, name, description, tags, roles, notes] of [
    ['slime', 'ranvora_v2_slime', 'RANVORA ver2 Slime', 'Squashed low-poly teal slime with flat base, two dark eyes and white glints — the first enemy of RANVORA ver2. Origin = ground contact point, faces +Z.',
      ['enemy', 'slime', 'monster', 'creature', 'cute', 'flat-shaded', 'vertex-colors'], ['enemy'],
      'Body and eyes as EnemyView draws them at rest. The hop, squash, telegraph and hit flash are code animations in src/combat/EnemyView.ts and are not baked into the GLB.'],
    ['slimeGel', 'ranvora_v2_slime_gel', 'RANVORA ver2 Slime Gel', 'Glowing teal crystal of slime jelly (スライムゼリー), the material dropped by slimes.',
      ['item', 'pickup', 'material', 'crystal', 'gem', 'slime', 'emissive'], ['pickup', 'item'],
      'In game it floats and spins; that motion is code, not in the GLB. Lifted 0.16 m so it rests on the ground.']
  ]) {
    const rel = `assets/ranvora-ver2/${key === 'slime' ? 'enemies' : 'items'}/${id}.glb`;
    const { glb, size, raw } = await write(key, rel);
    records.push(record({
      id, name, category: key === 'slime' ? 'character' : 'item', file: rel, tags, gameRoles: roles, animated: false, description,
      sourceFile: 'src/combat/EnemyView.ts', input: null, glb, size,
      units: { metresPerUnit: 1, nativeSize: size, suggestedSizeMetres: size, upAxis: 'Y' },
      optimization: { tool: 'three.js GLTFExporter → glTF Transform 4: dedup, weld, prune', sourceBytes: raw.length, outputBytes: glb.length }, notes
    }));
  }
  return records;
}

// ---------------------------------------------------------------- records
function record({ id, name, category, file, tags, gameRoles, animated, description, sourceFile, input, glb, size, units, optimization, notes, extra = {} }) {
  return {
    id, name, title: name, collection: 'ranvora-ver2', category, format: 'GLB', type: 'model',
    tags: [...new Set(['ranvora-ver2', 'ranvora', 'lowpoly', ...tags])], gameRoles, climbable: false, animated, description,
    file, localPath: file, thumbnail: `thumbnails/ranvora-ver2/${id}.png`,
    license: 'UNKNOWN', author: 'Yuji5124', source: 'RANVORA ver2',
    sourceUrl: `${REPO}/blob/${COMMIT}/${sourceFile}`, sourceFile, sourceRevision: COMMIT, ...(input ? { sourceSha256: sha256(input) } : {}),
    licenseEvidence: 'Original work made for the owner\'s own game RANVORA ver2 (Yuji5124/RANVORA-ver2). No licence has been declared yet, so it is recorded as UNKNOWN until the owner chooses one.',
    units, optimization, notes, recommendedFor: ['ranvora-ver2', 'threejs', 'lowpoly'], addedAt: ADDED_AT, ...extra
  };
}

const src = await sourceDir();
await fs.rm(outRoot, { recursive: true, force: true });
const records = [...await importHeroes(src), ...await importProcedural(src)];
await fs.rm(thumbDir, { recursive: true, force: true });
await renderThumbnails(thumbDir, records.map(r => path.join(root, r.file)));
const index = JSON.parse(await fs.readFile(dataFile, 'utf8')).filter(a => a.collection !== 'ranvora-ver2');
await fs.writeFile(dataFile, JSON.stringify([...index, ...records], null, 2) + '\n');
console.log(`Imported ${records.length} RANVORA ver2 models.`);
