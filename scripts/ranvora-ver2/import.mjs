// Imports the 3D data of RANVORA ver2 (Yuji5124/RANVORA-ver2) into NEXUS.
//   pinned commit → heroes (.gltf.json → GLB, data unchanged)
//   → procedural props / log cabin / slime built by ver2's own code in headless
//     Chromium and exported with three.js GLTFExporter
//   → assets/ranvora-ver2/ → thumbnails → index records (collection "ranvora-ver2").
// Run `npm run scan` afterwards (the npm script does it for you).
//
// Source: a RANVORA ver2 checkout. By default it is fetched into
// .cache/ranvora-ver2 at the pinned commit; set RANVORA_VER2_DIR to use an
// existing checkout (it must be at the pinned commit and have node_modules).
