async function importHeroes(src) {
  const heroes = [
    ['traveler.gltf.json', 'ranvora_v2_traveler', 'RANVORA ver2 Traveler (謎の旅人)',
      'Default hero of RANVORA ver2: a hooded mysterious traveler, about 3.5 heads tall, blue-grey hood and cloak, cream inner tunic, leather belt and boots, two softly glowing eyes in the hood shadow. Carries a sword and a staff (separate meshes on the hand bones) and a magic effect mesh.',
      ['traveler', 'hooded', 'cloak', 'chibi', 'hero', 'player', 'fantasy', 'sword', 'staff', 'magic'], 1.32,
      'Generated by blender/traveler.py: new body mesh on the original hero skeleton; animations copied from the original glTF without resampling.'],
    ['ranvora_chibi.gltf.json', 'ranvora_v2_original_hero', 'RANVORA Original Hero (初代主人公)',
      'The first RANVORA hero, kept by RANVORA ver2 for comparison and recovery: 3.5-head chibi adventurer with cloak, mask with glowing eyes, horns, scarf, coat and boots. Sword, staff and magic effect meshes included.',
      ['chibi', 'hero', 'player', 'fantasy', 'mask', 'horns', 'cloak', 'sword', 'staff', 'magic'], 1.3,
      'Made in Blender for RANVORA and carried over unchanged into RANVORA ver2.']
  ];
  const records = [];
  for (const [file, id, name, description, tags, gameScale, origin] of heroes) {
    const sourceFile = `src/assets/characters/${file}`;
    const input = await fs.readFile(path.join(src, sourceFile));
    const json = JSON.parse(input.toString('utf8'));
    const document = await io.readJSON({ json, resources: {} });
    const rel = `assets/ranvora-ver2/characters/${id}.glb`;
    const { glb, size, clips } = await writeGlb(document, rel, false);
    const joints = json.skins?.[0]?.joints?.length ?? 0;
    records.push(record({
      id, name, category: 'character', file: rel, tags: ['character', 'humanoid', 'rigged', 'animated', ...tags],
      gameRoles: ['player', 'character'], animated: true,
      description: `${description} Rig: ${joints} bones. ${clips.length} clips: ${clips.join(', ')}. Front faces +Z.`,
      sourceFile, input, glb, size,
      units: { metresPerUnit: 1, nativeSize: size, suggestedSizeMetres: size.map(v => Number((v * gameScale).toFixed(3))), upAxis: 'Y', front: '+Z', gameScale },
      optimization: { tool: 'glTF Transform 4: embedded .gltf.json → GLB (geometry, skin and animation data unchanged)', sourceBytes: input.length, outputBytes: glb.length },
      notes: `${origin} Both heroes share the same 33-bone skeleton and 7 clips, so animations and attack timing are interchangeable. RANVORA ver2 scales the model by ${gameScale} in game.`,
      extra: { skeleton: { joints, sharedWith: id === 'ranvora_v2_traveler' ? 'ranvora_v2_original_hero' : 'ranvora_v2_traveler' } }
    }));
  }
  return records;
}

